const DICTS: Record<Locale, Record<string, string>> = { pl: PL, en: EN, fr: FR };

@Injectable({ providedIn: 'root' })
export class I18nService {
  readonly locale = signal<Locale>(parseLocale(localStorage.getItem('pharma-locale')));

  constructor(private http: HttpClient) {}

  // Słownik kategorii
  private readonly CATEGORIES: Record<string, Record<Locale, string>> = {
    'analgesic': { pl: 'Przeciwbólowe', en: 'Analgesics', fr: 'Analgésiques' },
    'antibiotic': { pl: 'Antybiotyki', en: 'Antibiotics', fr: 'Antibiotiques' },
    'vitamin': { pl: 'Witaminy', en: 'Vitamins', fr: 'Vitamines' },
    'other': { pl: 'Inne', en: 'Other', fr: 'Autre' },
    'układ pokarmowy': { pl: 'Układ pokarmowy', en: 'Digestive system', fr: 'Système digestif' },
    'przeciwhistaminowe': { pl: 'Przeciwhistaminowe', en: 'Antihistamines', fr: 'Antihistaminiques' },
    'przeciwbólowe': { pl: 'Przeciwbólowe', en: 'Analgesics', fr: 'Analgésiques' },
    'antybiotyki': { pl: 'Antybiotyki', en: 'Antibiotics', fr: 'Antibiotiques' }
  };

  t(key: string): string {
    const loc = this.locale();
    return DICTS[loc][key] ?? DICTS.pl[key] ?? key;
  }

  // Tłumaczenie kategorii
  categoryLabel(category: string): string {
    const lower = category.toLowerCase();
    return this.CATEGORIES[lower] ? this.CATEGORIES[lower][this.locale()] : category;
  }

  statusLabel(status: string): string {
    const key = `status.${status}`;
    const v = this.t(key);
    return v !== key ? v : status;
  }

  entityLabel(type: string): string {
    const key = `entity.${type}`;
    return this.t(key) !== key ? this.t(key) : type;
  }

  setLocale(locale: Locale, persistServer = true): void {
    this.locale.set(locale);
    localStorage.setItem('pharma-locale', locale);
    if (persistServer) {
      const theme = localStorage.getItem('pharma-theme') || 'light';
      this.http.put(`${environment.apiUrl}/preferences`, { locale, theme }).subscribe();
    }
  }

  loadFromServer(): void {
    this.http.get<{ locale: string }>(`${environment.apiUrl}/preferences`).subscribe({
      next: (p) => this.locale.set(parseLocale(p.locale))
    });
  }
}
